# Названия в каталоге, которые не совпадают с SMSFast дословно.
_NAME_ALIASES: dict[str, str] = {
    "юар": "южная африка",
    "сша": "сша",  # приоритет обычной страны, а не «виртуальной» или T-Mobile
    "дем. конго": "дем.конго",
}


def normalize_name(name: str) -> str:
    """Нормализует название страны для сравнения каталогов."""
    text = name.strip().lower().replace("ё", "е")
    text = re.sub(r"[^a-zа-я0-9]+", "", text)
    return text


_normalize = normalize_name


def _build_index() -> dict[str, int]:
    index: dict[str, int] = {}
    for api_id, name in SMSFAST_COUNTRIES:
        key = _normalize(name)
        # Первое точное совпадение важнее «виртуальных» дублей.
        index.setdefault(key, api_id)
    for catalog_name, provider_name in _NAME_ALIASES.items():
        provider_key = _normalize(provider_name)
        if provider_key in index:
            index[_normalize(catalog_name)] = index[provider_key]
    return index


_INDEX = _build_index()


def provider_country_id(name: str) -> int | None:
    """Возвращает `country` для API SMSFast по названию страны каталога."""
    key = _normalize(name)
    direct = _INDEX.get(key)
    if direct is not None:
        return direct
    alias = _NAME_ALIASES.get(name.strip().lower())
    if alias is not None:
        return _INDEX.get(_normalize(alias))
    return None


def provider_country_name(api_id: int) -> str | None:
    for country_id, name in SMSFAST_COUNTRIES:
        if country_id == api_id:
            return name
    return None
